-- =============================================================================
-- ECX Visitor Management System — Full Database Schema (reference)
-- PostgreSQL 15+ | Matches the schema produced by the applied EF Core 10.0.9
-- migrations (see docs/database_documentation.md §29 Migration History).
-- =============================================================================
--
-- IMPORTANT
-- --------
-- * The production database is created and maintained by EF Core migrations
--   (dotnet ef database update). This script is a DOCUMENTATION reference that
--   reproduces the same tables, columns, types, defaults, FKs and indexes.
-- * There are NO native PostgreSQL ENUM types. All status/type/role fields are
--   stored as VARCHAR and validated in the application layer (backend/Models/
--   Enums.cs). Values such as 'Approved', 'Pending', 'Admin' are plain strings.
-- * All primary keys use GENERATED BY DEFAULT AS IDENTITY (not ALWAYS) so seed
--   scripts may insert explicit IDs.
-- * The ONLY non-null column defaults in the database are:
--     - appointments.has_properties                = false
--     - appointment_properties.property_name       = '' (empty string)
--   All other defaults are applied in application code.
--
-- Constraint naming in this file is clean and readable; the live database uses
-- EF Core's generated names (PK_<table>, FK_<table>_<target>_<column>,
-- IX_<table>_<column>, plus redundant "2200_*_not_null" CHECK constraints).
-- =============================================================================

BEGIN;

-- =============================================================================
-- 1. REFERENCE & IDENTITY
-- =============================================================================

CREATE TABLE departments (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(100) NOT NULL,
    description TEXT,
    location    VARCHAR(100),
    phone       VARCHAR(20),
    email       VARCHAR(100),
    is_active   BOOLEAN NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ,
    CONSTRAINT pk_departments PRIMARY KEY (id)
);

CREATE TABLE visitors (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    full_name   VARCHAR(100) NOT NULL,
    phone       VARCHAR(20) NOT NULL,
    email       VARCHAR(100) NOT NULL,
    address     TEXT NOT NULL,
    national_id VARCHAR(50),
    organization VARCHAR(100),
    gender      VARCHAR(10),
    photo_url   TEXT,
    is_active   BOOLEAN NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ,
    CONSTRAINT pk_visitors PRIMARY KEY (id),
    CONSTRAINT uq_visitors_email UNIQUE (email),
    CONSTRAINT uq_visitors_national_id UNIQUE (national_id)
);
CREATE INDEX ix_visitors_full_name ON visitors (full_name);

CREATE TABLE users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    full_name     VARCHAR(100) NOT NULL,
    email         VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(50) NOT NULL,
    is_active     BOOLEAN NOT NULL,
    last_login    TIMESTAMPTZ,
    employee_id   INTEGER,
    visitor_id    INTEGER,
    created_at    TIMESTAMPTZ NOT NULL,
    updated_at    TIMESTAMPTZ,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT fk_users_visitors FOREIGN KEY (visitor_id)
        REFERENCES visitors (id) ON DELETE NO ACTION
);
CREATE UNIQUE INDEX uq_users_employee_id ON users (employee_id) WHERE employee_id IS NOT NULL;
CREATE UNIQUE INDEX uq_users_visitor_id ON users (visitor_id) WHERE visitor_id IS NOT NULL;

CREATE TABLE employees (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    full_name     VARCHAR(100) NOT NULL,
    phone         VARCHAR(20) NOT NULL,
    email         VARCHAR(100) NOT NULL,
    department_id INTEGER NOT NULL,
    position      VARCHAR(100) NOT NULL,
    office_number VARCHAR(20),
    status        VARCHAR(20) NOT NULL,
    user_id       INTEGER,
    created_at    TIMESTAMPTZ NOT NULL,
    updated_at    TIMESTAMPTZ,
    CONSTRAINT pk_employees PRIMARY KEY (id),
    CONSTRAINT uq_employees_email UNIQUE (email),
    CONSTRAINT fk_employees_departments FOREIGN KEY (department_id)
        REFERENCES departments (id) ON DELETE CASCADE,
    CONSTRAINT fk_employees_users FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE NO ACTION
);
CREATE INDEX ix_employees_department_id ON employees (department_id);
CREATE INDEX ix_employees_full_name ON employees (full_name);
CREATE UNIQUE INDEX uq_employees_user_id ON employees (user_id) WHERE user_id IS NOT NULL;

-- =============================================================================
-- 2. APPOINTMENTS & VISITS
-- =============================================================================

CREATE TABLE appointments (
