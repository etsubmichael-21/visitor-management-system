    visitor_id                       INTEGER NOT NULL,
    employee_id                      INTEGER NOT NULL,
    requested_date                   DATE NOT NULL,
    requested_start_time             TIMESTAMPTZ NOT NULL,
    requested_end_time               TIMESTAMPTZ NOT NULL,
    purpose                          VARCHAR(500) NOT NULL,
    status                           VARCHAR(30) NOT NULL,
    route_type                       VARCHAR(30),
    appointment_method               VARCHAR(30),
    employee_response                TIMESTAMPTZ,
    approval_date                    TIMESTAMPTZ,
    rejection_reason                 TEXT,
    reminder_email_sent              BOOLEAN NOT NULL,
    reminder_sms_sent                BOOLEAN NOT NULL,
    visitor_confirmed                BOOLEAN NOT NULL,
    check_in_allowed                 BOOLEAN NOT NULL,
    appointment_code                 VARCHAR(20),
    is_confidential                  BOOLEAN NOT NULL,
    notes                            TEXT,
    delegated_to_employee_id         INTEGER,
    original_employee_id             INTEGER,
    redirect_department_id           INTEGER,
    redirected_from_department_id    INTEGER,
    redirect_reason                  TEXT,
    assigned_at                      TIMESTAMPTZ,
    assigned_by                      INTEGER,
    assigned_department_id           INTEGER,
    assigned_employee_id             INTEGER,
    has_properties                   BOOLEAN NOT NULL DEFAULT false,
    attachment_file_name             VARCHAR(255),
    attachment_original_name         VARCHAR(255),
    attachment_content_type          VARCHAR(120),
    attachment_path                  VARCHAR(500),
    attachment_size                  BIGINT,
    attachment_uploaded_at           TIMESTAMPTZ,
    property_letter_file_name        VARCHAR(255),
    property_letter_original_name    VARCHAR(255),
    property_letter_content_type     VARCHAR(120),
    property_letter_path             VARCHAR(500),
    property_letter_size             BIGINT,
    property_letter_uploaded_at      TIMESTAMPTZ,
    created_at                       TIMESTAMPTZ NOT NULL,
    updated_at                       TIMESTAMPTZ,
    CONSTRAINT pk_appointments PRIMARY KEY (id),
    CONSTRAINT fk_appointments_visitors FOREIGN KEY (visitor_id)
        REFERENCES visitors (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_employees FOREIGN KEY (employee_id)
        REFERENCES employees (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_original_employee FOREIGN KEY (original_employee_id)
        REFERENCES employees (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_delegated_employee FOREIGN KEY (delegated_to_employee_id)
        REFERENCES employees (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_assigned_employee FOREIGN KEY (assigned_employee_id)
        REFERENCES employees (id) ON DELETE NO ACTION,
    CONSTRAINT fk_appointments_redirect_department FOREIGN KEY (redirect_department_id)
        REFERENCES departments (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_assigned_department FOREIGN KEY (assigned_department_id)
        REFERENCES departments (id) ON DELETE NO ACTION,
    CONSTRAINT fk_appointments_redirected_from_department FOREIGN KEY (redirected_from_department_id)
        REFERENCES departments (id) ON DELETE NO ACTION
);
CREATE INDEX ix_appointments_visitor_id ON appointments (visitor_id);
CREATE INDEX ix_appointments_employee_id ON appointments (employee_id);
CREATE INDEX ix_appointments_requested_date ON appointments (requested_date);
CREATE INDEX ix_appointments_status ON appointments (status);
CREATE INDEX ix_appointments_appointment_code ON appointments (appointment_code);
CREATE INDEX ix_appointments_delegated_to_employee_id ON appointments (delegated_to_employee_id);
CREATE INDEX ix_appointments_original_employee_id ON appointments (original_employee_id);
CREATE INDEX ix_appointments_redirect_department_id ON appointments (redirect_department_id);
CREATE INDEX ix_appointments_redirected_from_department_id ON appointments (redirected_from_department_id);
CREATE INDEX ix_appointments_assigned_department_id ON appointments (assigned_department_id);
CREATE INDEX ix_appointments_assigned_employee_id ON appointments (assigned_employee_id);

CREATE TABLE visits (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    visitor_id            INTEGER NOT NULL,
    employee_id           INTEGER NOT NULL,
    appointment_id        INTEGER,
    purpose               VARCHAR(500) NOT NULL,
    visit_date            DATE NOT NULL,
    check_in_time         TIMESTAMPTZ,
    check_out_time        TIMESTAMPTZ,
    status                VARCHAR(20) NOT NULL,
    badge_number          VARCHAR(50),
    security_officer      VARCHAR(100),
    remark                TEXT,
    is_destination_known  BOOLEAN NOT NULL,
    redirect_note         TEXT,
    created_at            TIMESTAMPTZ NOT NULL,
    updated_at            TIMESTAMPTZ,
    CONSTRAINT pk_visits PRIMARY KEY (id),
    CONSTRAINT fk_visits_visitors FOREIGN KEY (visitor_id)
        REFERENCES visitors (id) ON DELETE RESTRICT,
    CONSTRAINT fk_visits_employees FOREIGN KEY (employee_id)
        REFERENCES employees (id) ON DELETE RESTRICT,
    CONSTRAINT fk_visits_appointments FOREIGN KEY (appointment_id)
        REFERENCES appointments (id) ON DELETE SET NULL
);
CREATE INDEX ix_visits_visitor_id ON visits (visitor_id);
CREATE INDEX ix_visits_employee_id ON visits (employee_id);
CREATE INDEX ix_visits_appointment_id ON visits (appointment_id);
CREATE INDEX ix_visits_status ON visits (status);
CREATE INDEX ix_visits_visit_date ON visits (visit_date);
CREATE INDEX ix_visits_check_in_time ON visits (check_in_time);

