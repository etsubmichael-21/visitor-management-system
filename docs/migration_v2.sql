-- =============================================================================
-- MIGRATION 2 — 20260731074958_AddRouteType
-- =============================================================================
-- Introduces the appointment routing concept: a visitor books directly with an
-- employee (DirectEmployee) or asks reception to route them (Reception).

ALTER TABLE appointments ADD COLUMN route_type VARCHAR(30);

-- =============================================================================
-- MIGRATION 3 — 20260731110014_AddAppointmentMethodAndAssignment
-- =============================================================================
-- Adds how the appointment was created (ReceptionAssistance / ScheduleMyself)
-- plus the reception assignment workflow columns (assigned department/employee,
-- assigner and timestamp, redirect source department and reason).

ALTER TABLE appointments
    ADD COLUMN appointment_method        VARCHAR(30),
    ADD COLUMN assigned_at               TIMESTAMPTZ,
    ADD COLUMN assigned_by               INTEGER,
    ADD COLUMN assigned_department_id    INTEGER,
    ADD COLUMN assigned_employee_id      INTEGER;

ALTER TABLE appointments
    ADD CONSTRAINT fk_appointments_assigned_department FOREIGN KEY (assigned_department_id)
        REFERENCES departments (id) ON DELETE NO ACTION,
    ADD CONSTRAINT fk_appointments_assigned_employee FOREIGN KEY (assigned_employee_id)
        REFERENCES employees (id) ON DELETE NO ACTION,
    ADD CONSTRAINT fk_appointments_redirected_from_department FOREIGN KEY (redirected_from_department_id)
        REFERENCES departments (id) ON DELETE NO ACTION;

CREATE INDEX ix_appointments_assigned_department_id ON appointments (assigned_department_id);
CREATE INDEX ix_appointments_assigned_employee_id ON appointments (assigned_employee_id);
CREATE INDEX ix_appointments_redirected_from_department_id ON appointments (redirected_from_department_id);

-- =============================================================================
-- MIGRATION 4 — 20260731195610_AddSupportingLetter
-- =============================================================================
-- Adds the single supporting-letter upload columns on appointments
-- (distinct from the later appointment_attachments table).

ALTER TABLE appointments
    ADD COLUMN attachment_file_name          VARCHAR(255),
    ADD COLUMN attachment_original_name      VARCHAR(255),
    ADD COLUMN attachment_content_type       VARCHAR(120),
    ADD COLUMN attachment_path               VARCHAR(500),
    ADD COLUMN attachment_size               BIGINT,
    ADD COLUMN attachment_uploaded_at        TIMESTAMPTZ;

-- =============================================================================
-- MIGRATION 5 — 20260804123642_AddAppointmentProperties
-- =============================================================================
-- Introduces the declared-property workflow: the appointment_properties table
-- and the property authorization letter upload columns on appointments.

ALTER TABLE appointments
    ADD COLUMN property_letter_file_name       VARCHAR(255),
    ADD COLUMN property_letter_original_name   VARCHAR(255),
    ADD COLUMN property_letter_content_type    VARCHAR(120),
    ADD COLUMN property_letter_path            VARCHAR(500),
    ADD COLUMN property_letter_size            BIGINT,
    ADD COLUMN property_letter_uploaded_at     TIMESTAMPTZ;

CREATE TABLE appointment_properties (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY,
    appointment_id   INTEGER NOT NULL,
    property_type    VARCHAR(100) NOT NULL,
    brand            VARCHAR(100),
    model            VARCHAR(100),
    serial_number    VARCHAR(100),
    asset_tag_number VARCHAR(100),
    quantity         INTEGER NOT NULL,
    description      TEXT,
    is_verified      BOOLEAN NOT NULL,
    verified_at      TIMESTAMPTZ,
    verified_by_user_id INTEGER,
    created_at       TIMESTAMPTZ NOT NULL,
    updated_at       TIMESTAMPTZ,
    CONSTRAINT pk_appointment_properties PRIMARY KEY (id),
    CONSTRAINT fk_appointment_properties_appointments FOREIGN KEY (appointment_id)
        REFERENCES appointments (id) ON DELETE CASCADE,
    CONSTRAINT fk_appointment_properties_verifier FOREIGN KEY (verified_by_user_id)
        REFERENCES users (id) ON DELETE RESTRICT
);
CREATE INDEX ix_appointment_properties_appointment_id ON appointment_properties (appointment_id);
CREATE INDEX ix_appointment_properties_is_verified ON appointment_properties (is_verified);
CREATE INDEX ix_appointment_properties_verified_by_user_id ON appointment_properties (verified_by_user_id);

-- =============================================================================
-- MIGRATION 6 — 20260804181825_AddVisitorPropertySelection
-- =============================================================================
-- Allows the visitor to declare whether they carry property items (has_properties
-- flag, default false) and to name their property item during booking (the
-- property_name column, empty-string default).

ALTER TABLE appointments ADD COLUMN has_properties BOOLEAN NOT NULL DEFAULT false;

ALTER TABLE appointment_properties ADD COLUMN property_name VARCHAR(255) NOT NULL DEFAULT '';

-- =============================================================================
-- MIGRATION 7 — 20260804200407_AddUnavailabilityTimeAndRepeat
-- =============================================================================
-- Extends employee_unavailability with an intra-day time window and a repeat
-- rule (used by the calendar's Add Unavailability dialog).

ALTER TABLE employee_unavailability
    ADD COLUMN start_time TIME,
    ADD COLUMN end_time   TIME,
    ADD COLUMN repeat     VARCHAR(20);

-- =============================================================================
-- MIGRATION 8 — 20260805064924_AddPropertyVerificationStatus
-- =============================================================================
-- Adds an explicit verification state to property items, distinguishing a
-- verified item from an item that was found to be additional at check-in.

ALTER TABLE appointment_properties ADD COLUMN verification_status VARCHAR(50);

-- =============================================================================
-- MIGRATION 9 — 20260807065634_AddCheckoutItems
-- =============================================================================
-- Adds the check-out item-return workflow: the security officer records which
-- declared property items are returned before the visitor leaves.

CREATE TABLE checkout_items (
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    visit_id                INTEGER NOT NULL,
    appointment_property_id INTEGER,
    item_name               VARCHAR(255) NOT NULL,
    description             TEXT,
    quantity                INTEGER NOT NULL,
    return_status           VARCHAR(30) NOT NULL,
    remarks                 TEXT,
    created_at              TIMESTAMPTZ NOT NULL,
    updated_at              TIMESTAMPTZ,
    CONSTRAINT pk_checkout_items PRIMARY KEY (id),
    CONSTRAINT fk_checkout_items_visits FOREIGN KEY (visit_id)
        REFERENCES visits (id) ON DELETE CASCADE,
    CONSTRAINT fk_checkout_items_appointment_properties FOREIGN KEY (appointment_property_id)
        REFERENCES appointment_properties (id) ON DELETE SET NULL
);
CREATE INDEX ix_checkout_items_visit_id ON checkout_items (visit_id);
CREATE INDEX ix_checkout_items_appointment_property_id ON checkout_items (appointment_property_id);
