-- =============================================================================
-- ECX Visitor Management System — Schema Evolution (reference)
-- PostgreSQL 15+ | EF Core 10.0.9
-- =============================================================================
--
-- This script documents the INCREMENTAL schema changes applied by EF Core to
-- reach the current 21-table design. It mirrors the migration history recorded
-- in __EFMigrationsHistory (see docs/database_documentation.md §29). Each
-- numbered section below maps to one applied EF migration: MIGRATION 1 is the
-- InitialCreate base schema; MIGRATION 2–9 are the follow-up changes. The full
-- final schema is docs/visitor_management.sql.
--
-- NOTE: In the live database these changes were applied by `dotnet ef database
-- update`, NOT by running this script. This file is a documentation reference
-- of what each migration introduced.
-- =============================================================================

-- =============================================================================
-- MIGRATION 1 — 20260713082828_InitialCreate
-- =============================================================================
-- The base schema. Creates 19 of the 21 tables (the two later additions are
-- appointment_properties and checkout_items). Columns, types and constraints
-- for these tables match the corresponding sections of docs/visitor_management.sql.

CREATE TABLE departments (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(100) NOT NULL,
    description TEXT,
    location    VARCHAR(100),
    phone       VARCHAR(20),
    email       VARCHAR(100),
    is_active   BOOLEAN NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ,
    CONSTRAINT pk_departments PRIMARY KEY (id)
);

CREATE TABLE visitors (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    full_name    VARCHAR(100) NOT NULL,
    phone        VARCHAR(20) NOT NULL,
    email        VARCHAR(100) NOT NULL,
    address      TEXT NOT NULL,
    national_id  VARCHAR(50),
    organization VARCHAR(100),
    gender       VARCHAR(10),
    photo_url    TEXT,
    is_active    BOOLEAN NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL,
    updated_at   TIMESTAMPTZ,
    CONSTRAINT pk_visitors PRIMARY KEY (id),
    CONSTRAINT uq_visitors_email UNIQUE (email)
);

CREATE TABLE users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    full_name     VARCHAR(100) NOT NULL,
    email         VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(50) NOT NULL,
    is_active     BOOLEAN NOT NULL,
    last_login    TIMESTAMPTZ,
    employee_id   INTEGER,
    visitor_id    INTEGER,
    created_at    TIMESTAMPTZ NOT NULL,
    updated_at    TIMESTAMPTZ,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT fk_users_visitors FOREIGN KEY (visitor_id)
        REFERENCES visitors (id) ON DELETE NO ACTION
);
CREATE UNIQUE INDEX uq_users_employee_id ON users (employee_id) WHERE employee_id IS NOT NULL;
CREATE UNIQUE INDEX uq_users_visitor_id ON users (visitor_id) WHERE visitor_id IS NOT NULL;

CREATE TABLE employees (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    user_id       INTEGER,
    department_id INTEGER NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    email         VARCHAR(100) NOT NULL,
    phone         VARCHAR(20) NOT NULL,
    position      VARCHAR(100) NOT NULL,
    office_number VARCHAR(20),
    status        VARCHAR(20) NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL,
    updated_at    TIMESTAMPTZ,
    CONSTRAINT pk_employees PRIMARY KEY (id),
    CONSTRAINT uq_employees_email UNIQUE (email),
    CONSTRAINT fk_employees_departments FOREIGN KEY (department_id)
        REFERENCES departments (id) ON DELETE CASCADE,
    CONSTRAINT fk_employees_users FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE NO ACTION
);
CREATE UNIQUE INDEX uq_employees_user_id ON employees (user_id) WHERE user_id IS NOT NULL;

CREATE TABLE appointments (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    visitor_id           INTEGER NOT NULL,
    employee_id          INTEGER NOT NULL,
    requested_date       DATE NOT NULL,
    requested_start_time TIMESTAMPTZ NOT NULL,
    requested_end_time   TIMESTAMPTZ NOT NULL,
    purpose              VARCHAR(500) NOT NULL,
    status               VARCHAR(30) NOT NULL,
    employee_response    TIMESTAMPTZ,
    approval_date        TIMESTAMPTZ,
    reminder_email_sent  BOOLEAN NOT NULL,
    reminder_sms_sent    BOOLEAN NOT NULL,
    visitor_confirmed    BOOLEAN NOT NULL,
    check_in_allowed     BOOLEAN NOT NULL,
    appointment_code     VARCHAR(20),
    is_confidential      BOOLEAN NOT NULL,
    delegated_to_employee_id INTEGER,
    original_employee_id      INTEGER,
    redirect_department_id    INTEGER,
    rejection_reason     TEXT,
    notes                TEXT,
    created_at           TIMESTAMPTZ NOT NULL,
    updated_at           TIMESTAMPTZ,
    CONSTRAINT pk_appointments PRIMARY KEY (id),
    CONSTRAINT fk_appointments_visitors FOREIGN KEY (visitor_id)
        REFERENCES visitors (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_employees FOREIGN KEY (employee_id)
        REFERENCES employees (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_delegated_employee FOREIGN KEY (delegated_to_employee_id)
        REFERENCES employees (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_original_employee FOREIGN KEY (original_employee_id)
        REFERENCES employees (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_redirect_department FOREIGN KEY (redirect_department_id)
        REFERENCES departments (id) ON DELETE RESTRICT
);

